func TestGradeTypeString(t *testing.T) {

	input := []GradeType{
		Assignment,
		Exam,
		Essay,
		GradeType(-1),
	}

	expected := []string{
		"assignment",
		"exam",
		"essay",
		"",
	}

	for i, gradeType := range input {
		actual := gradeType.String()
		if actual != expected[i] {
			t.Errorf("GradeType(%d).String() should be %q; got %q", gradeType, expected[i], actual)
		}
	}
}
